"""Design a protein with REQUESTED residue contacts: the interaction stream as a user-facing handle (S2 arm A/B/C checkpoints).

Spec (JSON, residue numbers are 1-based positions of the designed chain)::

    {"length": 100,
     "contacts":  [[12, 78, "hbond"], [5, 90, "salt_bridge"], [30, 65, "any"]],
     "negatives": [[20, 60]],
     "n_designs": 4, "seed": 0, "label_temp": 0.5, "lag": 0.4, "cfg_w": 1.0, "mode": "pinned"}

* TWO-CHAIN COMPLEXES (optional ``chains: [L1, L2]``; ``length`` then omitted or = L1 + L2, the normalised spec carries both): chain A is designed with L1 residues, chain B with L2, both de novo from noise (the real RFD4
  pipeline builds the batch: one expandable-segment sentinel per chain, ``chain_iid`` 0 / 1, no covalent path between the chains; no target structure is needed). GLOBAL NUMBERING (1-based, in every contact,
  negative, map and report): chain A = residues 1..L1, chain B = L1+1..L1+L2 (token order of the model). A contact [i, j, class] with i <= L1 < j is INTER-chain; its class names are the SAME words, the label state is the
  inter-chain state 11 + type (ring_data / gate_c: 11 hbond, 12 salt_bridge, 14 hydrophobic, 15 pi_stack, 16 pi_cation, 17 disulfide, 18 vdw (``any``), 21 pi_hbond = ``inter_<class>``); ionic / metal / halogen are
  rejected as for a single chain (inter_ionic 13, inter_metal 19, inter_halogen 20 are never measurable on protein-only designs). The separation rule |i-j| >= 3 applies to pairs INSIDE a chain only. The sampler
  forbids, per pair, inter states inside a chain and intra states across chains (``ring_flow.class_forbid``). Outputs: PDBs with chains A / B (own residue numbering), ``designs.fasta`` with one record per chain
  (``design_0000_A``, ``design_0000_B``), per contact ``inter`` + RING state names ``inter_<class>``, per design an ``interface`` block (inter-chain CA<=8 pairs, residue pairs / atom pairs within 4.5 A,
  interface residues per chain, a buried-surface PROXY from biotite SASA of the heavy-atom model, and after ``ring-check`` the number of RING inter-chain contacts by class at every window).
* ``contacts``: [i, j, class] with class in hbond | salt_bridge | hydrophobic | pi_stack | pi_cation | pi_hbond | disulfide | vdw | any. The class is mapped to the intra-chain
  state of the 23-state RING label space exactly as ``ring_data`` / ``gate_c`` index it (state = position in ``RING_INTERACTION_TYPES``, 0..10; single chain, so never the inter-chain states 11..21).
  ``any`` = "some close contact": shown as ``vdw`` (state 7, the generic heavy-atom proximity class); the report then accepts any contact class for it. REJECTED (cannot be satisfied/measured in a
  protein-only design): ``ionic`` (RING IONIC edges come out of the gate_c converter as ``salt_bridge``, state 1: ask for that), ``metal`` and ``halogen`` (no such atoms in the designed chain).
  The spec written to the tar (``spec.json``, normalised: contact / negative dicts, ``warnings``) is accepted by the loader again.
* ``negatives``: pairs shown as NO_INTERACTION (state 22) at every step ("these two must NOT touch").
* ``mode`` ``pinned``: ONLY these pairs are shown, from step 0 to the last step; every other pair stays MASK (sampler mode ``pinned``). ``hybrid``: the pinned labels are shown and re-written after every step, every
  OTHER pair is generated by the model's own head on the ``generated`` schedule (``label_temp`` = TRIADR_RING_TEMP, ``lag`` = TRIADR_RING_LAG: labels appear later with larger lag; inter-chain states masked).
* ``cfg_w`` != 1: stream classifier-free guidance (TRIADR_STREAM_CFG): pred = pred_masked + w (pred_cond - pred_masked) at every step, 2 denoiser passes per step.
* separation |i-j| >= 3 (RING reports no closer pair); |i-j| < 8 draws a warning in the report (local, not a tertiary constraint).

Output: ONE tar.gz (``--out-tar``) with ``designs/design_NNNN.pdb`` (ALL-ATOM, the co-generated sequence), ``designs.fasta``, ``map.json`` (pinned pairs, and for ``hybrid`` the final generated map of every design),
``report.json`` (per design and per requested contact: CA-CA distance and ``ca_ok`` <= 8 A; ``min_heavy_dist`` over all heavy atoms and ``heavy_ok`` <= 4.5 A; ``class_geom_ok`` = a class-specific geometric proxy
(hbond: N/O pair <= 3.5 A; salt_bridge/ionic: opposite-charge N/O pair <= 4.5 A; hydrophobic: side-chain C-C <= 5 A between hydrophobic residues; pi_stack: ring centroids <= 6.5 A; disulfide: SG-SG <= 2.5 A; other: heavy_ok);
``ring_state`` / ``ring_ok`` = what the real RING 4 binary measures on the decoded structure (added by the ``ring-check`` step, same code as ``gate_c``); negatives: ``ca_far_ok`` (> 8 A), ``heavy_far_ok`` (> 4.5 A));
``pins_verified`` = at EVERY sampler step the pinned pairs were checked in the input of the denoiser), ``spec.json``. No per-design files are written: the tar is built in memory.
TWO RING WINDOWS (``ring-check``, ``--ring-w`` > env ``DWC_RING_W`` > option ``ring_w`` in the spec, default ``none,0.25``): every design is RING-measured at the binary's DEFAULT vdw window (the STRICT window:
``ring_state`` / ``ring_ok`` / ``ring_none_ok`` keep their meaning) AND at an explicit ``-w 0.25`` (the TOLERANT window: ``ring_state_w0.25`` / ``ring_ok_w0.25`` / ``ring_none_ok_w0.25``, per-class and per-design
aggregates ``ring_ok_w0.25`` ..., the HEADLINE class-satisfaction number, labelled 'tolerant RING window -w 0.25' in ``report.ring.headline``). Why: RING's default vdw window is razor thin (the checked binary's omitted
-w behaves like -w 0.01 although its help says 0.5; a carbon-carbon witness survives only at 3.367-3.433 A), so a decoded structure whose side chains differ from the native by ~0.1 A flips vdw / hydrophobic
edges: native structures re-decoded by the frozen autoencoder retain only 45 % / 42 % of their vdw / hydrophobic classes at the default window but 89 % / 100 % at -w 0.25, and the contacts tool realises the
requested vdw / hydrophobic classes of dense requests at 0.22 / 0.26 (default window) vs 0.69 / 0.71 (-w 0.25) (N015 / ae_ceiling / dwc_class_fidelity rescore). ``report.ring`` records binary, version, flags and the
-w of every window; ANY RING failure at ANY window makes the design unmeasured (cleared at every window, counted as unsatisfied, exit 3).
RING bookkeeping (``ring-check``): every satisfaction rate whose name starts with ``ring`` has the denominator ALL requested designs (a design whose RING step failed counts as NOT satisfied);
``ring_ok_measured_only`` is the rate over the measured designs only; ``n_requested`` / ``n_measured`` are given per contact, per class (``aggregate.by_class``) and per design (``summary``).
Exit codes: 0 ok | 2 bad spec / arguments / environment | 3 the RING step failed for at least one design (the tar is kept, ``report.status.ok`` false, ``DWC FAIL`` printed) |
4 pin verification failed (a requested pair was missing from the denoiser input at some step or in the final state). Arm Z (stream forced all-MASK) is refused.

    python -m triadj_ext.s2.design_with_contacts run --spec spec.json --arm A --ckpt <chk>-ema.ckpt --out-tar /tmp/x.tar.gz
    python -m triadj_ext.s2.design_with_contacts ring-check --tar /tmp/x.tar.gz [--ring-w none,0.25]   # host step: RING binary, adds ring_state / ring_ok (+ ring_ok_w0.25) to report.json

Placement: 1 H100 (see design_with_contacts.sbatch). The pure parts (spec, maps, geometry, report) import numpy only and are unit-tested in tests/test_design_with_contacts.py.
"""
