def setup_run(args) -> dict:
    """Model + sampler context, loaded ONCE (the 4-minute part of ``run``): reused by ``sample_spec`` for any number of specs (``dwc_class_fidelity drive``)."""
    import torch

    from triadj_ext.s2 import cond_gen as CG

    t0 = time.time()
    device = torch.device(args.device)
    if device.type == "cuda":
        torch.backends.cuda.matmul.allow_tf32 = True
        torch.set_float32_matmul_precision("medium")
    amp = device.type == "cuda"
    model, meta = CG.load_model(args, device)
    log("init " + " ".join(f"{k}={v}" for k, v in meta.items()) + f" device={device} load_s={time.time() - t0:.0f}")
    gen_over = [f"generation.model.local_latents.simulation_step_params.tsr_k={args.tsr_k}", *[o for chunk in args.gen_overrides for o in chunk.split()]]
    inf_cfg = CG.compose_inference_cfg(args.configs_dir, gen_over)
    check_pin_capable(model)
    dev = model.device if isinstance(getattr(model, "device", None), torch.device) else device  # the device VanillaStrategy.generate uses for its own tensors
    check_model_on_device(model, dev)
    model.inf_cfg = inf_cfg
    model.guidance_model = None
    nsteps = int(inf_cfg.args.nsteps)
    src = CG.DeNovoBatches(args.denovo_cif)
    return {"model": model, "meta": meta, "device": device, "dev": dev, "amp": amp, "inf_cfg": inf_cfg, "nsteps": nsteps, "src": src, "t0": t0}


def sample_spec(ctx: dict, spec: dict, args) -> tuple:
    """Sample + decode ONE validated spec with the loaded model -> (report dict, tar members dict). The body of ``run`` after the model load (unchanged)."""
    import torch

    from rfproteina.search.vanilla import VanillaStrategy

    from triadj_ext import ring_flow as RF
    from triadj_ext.s2 import cond_gen as CG

    t0 = time.time()
    device, dev, amp, model, meta, nsteps, src = ctx["device"], ctx["dev"], ctx["amp"], ctx["model"], ctx["meta"], ctx["nsteps"], ctx["src"]
    if not isinstance(args.micro_batch, int) or isinstance(args.micro_batch, bool) or args.micro_batch < 1:
        raise ValueError(f"micro_batch must be an integer >= 1, got {args.micro_batch!r}")
    check_environment(spec["mode"])
    L, n = spec["length"], spec["n_designs"]
    pm = pinned_map(spec)
    pins = pins_of(pm)
    control = spec["mode"] == "masked"  # the untreated-sampler control of dwc_class_fidelity (the spec dict is relabelled there): the stream must be ALL-MASK, verified on EVERY valid pair at EVERY step
    chains = spec.get("chains")
    log(f"spec: L={L}{f' chains={chains} (A = 1..{chains[0]}, B = {chains[0] + 1}..{L})' if chains else ''} contacts={len(spec['contacts'])} negatives={len(spec['negatives'])} designs={n} mode={spec['mode']} label_temp={spec['label_temp']} lag={spec['lag']} cfg_w={spec['cfg_w']} nsteps={nsteps}")
    for w in spec["warnings"]:
        log("WARN " + w)
    env = {k: None for k in CG.KNOB_VARS}
    env.update({"TRIADR_RING_SAMPLER": spec["mode"], "TRIADR_RING_ISOLATE_RNG": None, "TRIADR_RING_PAIR_FORBID": "1" if chains else None, "TRIADR_RING_ALLOW_INTER": None})  # complexes: inter states only across chains, intra states only inside a chain (hybrid mode)
    if spec["mode"] == "hybrid":
        env["TRIADR_RING_TEMP"] = repr(spec["label_temp"])
        env["TRIADR_RING_LAG"] = repr(spec["lag"])
    if spec["cfg_w"] != 1.0:
        env["TRIADR_STREAM_CFG"] = repr(spec["cfg_w"])
    designs, seqs, pdbs, finals, pin_stats = [], [], [], [], {"steps": 0, "violations": 0, "checked_pairs": 0}
    for b0 in range(0, n, args.micro_batch):
        rows = list(range(b0, min(n, b0 + args.micro_batch)))
        batch = move_batch(src.batch([f"{spec['name']}_{r:04d}" for r in rows], [tuple(chains) if chains else L] * len(rows), keep_atom_array=True), dev)  # the pipeline builds CPU tensors: the encoder (add_clean_samples) is on the GPU
        gt = torch.as_tensor(pm, dtype=torch.int16)[None].expand(len(rows), L, L).contiguous()
        batch["ring_state_gt"] = gt.to(dev)  # a runtime key (not a dataclass field): moved explicitly, after move_batch
        check_batch_on_device(batch, dev)
        stats, restore = install_pin_check(model.fm, pins, dev, control=control)
        col = []
        RF.add_ring_sink(col.append)
        torch.manual_seed(spec["seed"] + 100003 * (b0 // args.micro_batch))
        try:
            with CG.env_set(**env), torch.autocast(device.type, dtype=torch.bfloat16, enabled=amp):
                out = VanillaStrategy().generate(model, batch)
        finally:
            restore()
            RF.remove_ring_sink(col.append)
        for k in pin_stats:
            pin_stats[k] += stats[k]
        if len(out) != len(rows):
            raise RuntimeError(f"decode returned {len(out)} designs for {len(rows)} rows")
        fin = col[-1]["ring_state"].numpy().astype(int) if col else None
        for k, res in enumerate(out):
            aa = res["generated_atom_array"]
            residues = residues_of(aa)
            if len(residues) != L:
                raise RuntimeError(f"decoded design has {len(residues)} residues, requested {L}")
            if chains:
                ids = [r.get("chain") for r in residues]
                if not (len(set(ids[:chains[0]])) == 1 and len(set(ids[chains[0]:])) == 1 and ids[0] != ids[chains[0]]):
                    raise RuntimeError(f"decoded chains do not match the requested lengths {chains}: chain ids by residue {ids[:3]}...{ids[chains[0] - 2:chains[0] + 2]}...{ids[-3:]}")
            designs.append(design_report(residues, spec))
            if chains:
                designs[-1]["chains"] = [{"id": ids[0], "length": chains[0], "sequence": sequence_of(residues[:chains[0]])}, {"id": ids[chains[0]], "length": chains[1], "sequence": sequence_of(residues[chains[0]:])}]
            seqs.append(sequence_of(residues))
            pdbs.append(pdb_text(aa))
            finals.append(None if fin is None else fin[k][:L, :L])
        log(f"progress designs={len(designs)}/{n} el_s={time.time() - t0:.0f}")
    if len(designs) != n or len(pdbs) != n:
        raise RuntimeError(f"the run produced {len(designs)} designs, the spec asks for {n}")
    # final-state check of the pinned pairs (pinned: the last state; hybrid: the overwrite after the last reveal)
    final_ok = final_state_ok(finals, pins, control)
    names = [f"design_{r:04d}" for r in range(n)]
    for d, nm, sq in zip(designs, names, seqs):
        d["design"], d["sequence"] = nm, sq
    report = {"schema": SCHEMA, "spec": spec, "model": {k: str(v) for k, v in meta.items()}, "nsteps": nsteps,
              "sampler": {"mode": spec["mode"], "label_temp": spec["label_temp"] if spec["mode"] == "hybrid" else None, "lag": spec["lag"] if spec["mode"] == "hybrid" else None,
                          "stream_cfg_w": spec["cfg_w"], "denoiser_passes_per_step": 2 if spec["cfg_w"] != 1.0 else 1},
              "pins_verified": {"steps_checked": pin_stats["steps"], "pairs_checked": pin_stats["checked_pairs"], "violations": pin_stats["violations"], "final_state_ok": final_ok,
                                "ok": bool(pin_stats["violations"] == 0 and final_ok and pin_stats["steps"] >= nsteps * -(-n // args.micro_batch)),
                                **({"control": True, "control_verified": bool(pin_stats["violations"] == 0 and final_ok and pin_stats["checked_pairs"] > 0 and pin_stats["steps"] >= nsteps * -(-n // args.micro_batch))} if control else {})},
              "designs": designs, "aggregate": aggregate_report(designs, spec), "ring": {"checked": False, "note": "run `ring-check` (host step) to add RING-measured states"},
              "seconds": time.time() - t0}
    finalize_status(report)
    maps = {"spec_pairs": "1-based residue numbers", "designs": {nm: map_record(f, spec) for nm, f in zip(names, finals)}}
    members = {"spec.json": json.dumps(spec, indent=1), "report.json": json.dumps(report, indent=1, default=float), "map.json": json.dumps(maps, indent=1),
               "designs.fasta": "".join(f">{nm} len={L} seed={spec['seed']} mode={spec['mode']}\n{sq}\n" for nm, sq in zip(names, seqs)) if not chains else
               "".join(f">{nm}_{c['id']} len={c['length']} seed={spec['seed']} mode={spec['mode']}\n{c['sequence']}\n" for nm, d in zip(names, designs) for c in d["chains"])}
    for nm, txt in zip(names, pdbs):
        members[f"designs/{nm}.pdb"] = txt
    return report, members


def run(args) -> dict:
    spec = load_spec(args.spec)
    check_environment(spec["mode"])
    ctx = setup_run(args)
    report, members = sample_spec(ctx, spec, args)
    n, pin_stats, final_ok = spec["n_designs"], report["pins_verified"], report["pins_verified"]["final_state_ok"]
    write_tar(args.out_tar, members)
    agg = report["aggregate"]["mean_design_summary"]
    log("satisfaction (mean over designs): " + " ".join(f"{k}={v:.3f}" for k, v in agg.items() if v is not None))
    log(f"pins_verified: steps={pin_stats['steps_checked']} pairs={pin_stats['pairs_checked']} violations={pin_stats['violations']} final_ok={final_ok} ok={report['pins_verified']['ok']}")
    log(f"done out_tar={args.out_tar} total_s={time.time() - ctx['t0']:.0f}")
    return report


# ------------------------------------------------------------------------------------------------------------------ RING check (host step)
def _clear_ring(d: dict) -> None:
    """Drop EVERY RING field of an earlier check, at every window (``ring_*`` and ``ring_*_w<w>`` on the design, its contacts and its negatives): a failed re-check must never leave an old success behind."""
    for items in (d["contacts"], d["negatives"]):
        for x in items:
            for k in [k for k in x if k.startswith("ring_")]:
                del x[k]
    for k in [k for k in d if k.startswith("ring_")]:
        del d[k]


def ring_check(tar_path: str, ring_bin: str | None = None, tmp_root: str | None = None, maps_out: dict | None = None, ring_w="strict") -> dict:
    """Run the RING 4 binary on every PDB of the tar (same code as gate_c: run_ring / parse_ring_edges / edges_to_state), add ``ring_state`` / ``ring_ok`` to every requested contact and
    ``ring_state`` / ``ring_none_ok`` to every negative of report.json, and rewrite the tar. ``ring_ok``: the measured type equals the requested one ('any': any positive type).
    ``ring_w``: the RING windows (see ``parse_ring_w``): 'strict' (default of this FUNCTION: the binary's default window only, as before: the field set callers such as ``dwc_class_fidelity`` expect), 'auto'
    (env ``DWC_RING_W`` > spec ``ring_w`` > ``none,0.25``: what the CLI uses without ``--ring-w``), or an explicit list / string. Each extra window w adds ``ring_state_w<w>`` / ``ring_ok_w<w>`` / ``ring_none_ok_w<w>`` (the strict
    window keeps the unsuffixed names), per-contact / per-class / per-design rates with the same suffix, and ``report['ring']['settings']``.
    Every earlier RING field is cleared first. A design whose RING step fails at ANY window gets ``ring_measured=False`` + ``ring_error`` (nothing partial survives) and counts as NOT satisfied in every ``ring_*``
    rate at every window (denominator = all designs; ``*_measured_only`` = over the measured ones); ``report['ring']['ok']`` is False and ``report['status']`` lists the failure: the CLI then exits non-zero
    (the tar is kept for diagnosis). ``maps_out`` collects the STRICT-window positives only."""
    import tempfile

    from triadj_ext.s2 import gate_c as G

    ring_bin = ring_bin or G.RING_BIN_DEFAULT
    mem = read_tar(tar_path)
    report = json.loads(mem["report.json"])
    spec = report["spec"]
    if isinstance(ring_w, str) and ring_w == "strict":
        windows = [None]
    elif isinstance(ring_w, str) and ring_w == "auto":
        windows = parse_ring_w(os.environ.get("DWC_RING_W") or spec.get("ring_w") or DEFAULT_RING_W)
    else:
        windows = parse_ring_w(ring_w)
    tags = [w_tag(w) for w in windows]
    base = tmp_root or tempfile.gettempdir()
    if os.path.abspath(base).startswith("/home"):  # per-design RING work files stay node-local (home inode quota)
        base = "/tmp"
    root = tempfile.mkdtemp(prefix="dwc_ring_", dir=base)
    n_ok = 0
    try:
        for d in report["designs"]:
            _clear_ring(d)
        for d in report["designs"]:
            nm = d["design"]
            pth = os.path.join(root, nm + ".pdb")
            cur = None
            try:
                with open(pth, "wb") as fh:
                    fh.write(mem[f"designs/{nm}.pdb"])
                pdb = G.parse_pdb(mem[f"designs/{nm}.pdb"].decode())
                states = {}
                two = bool(spec.get("chains"))
                if two:  # complexes: the chain of every residue index (gate_c indexes residues by (chain, resSeq, icode), so RING's cross-chain edges are already found; only the inter-chain STATE offset is added here)
                    cidx = np.empty(len(pdb["names"]), dtype=object)
                    for k_, r_ in pdb["index"].items():
                        cidx[r_] = k_[0]
                    inter_pair = cidx[:, None] != cidx[None, :]
                for w, tag in zip(windows, tags):
                    cur = w
                    edges = G.parse_ring_edges(run_ring_w(pth, os.path.join(root, f"{nm}_out{tag}"), ring_bin, w))
                    states[tag], _st = G.edges_to_state(edges, pdb)
                    if two:
                        st16 = states[tag].astype(np.int16)
                        sel = inter_pair & (st16 < INTER_OFFSET)
                        st16[sel] = np.where(st16[sel] < len(G.TYPES), st16[sel] + INTER_OFFSET, st16[sel])  # a typed intra state on a cross-chain pair is the inter state of the same type; none (22) stays 22
                        states[tag] = st16
                cur = None
                for w, tag in zip(windows, tags):  # every window measured: only now write any field
                    state = states[tag]
                    for c in d["contacts"]:
                        s_ = int(state[c["i"] - 1, c["j"] - 1])
                        pos = s_ < NO_INT  # 0..10 intra, 11..21 inter (complexes only), 22 none, 24 diagonal
                        c["ring_state" + tag] = (("inter_" if s_ >= INTER_OFFSET else "") + G.TYPES[s_ % INTER_OFFSET]) if pos else "none"
                        c["ring_ok" + tag] = bool(pos and (c["class"] == ANY_CLASS or G.TYPES[s_ % INTER_OFFSET] == c["class"]) and (s_ >= INTER_OFFSET) == bool(c.get("inter", False)))
                    for n in d["negatives"]:
                        s_ = int(state[n["i"] - 1, n["j"] - 1])
                        n["ring_state" + tag] = (("inter_" if s_ >= INTER_OFFSET else "") + G.TYPES[s_ % INTER_OFFSET]) if s_ < NO_INT else "none"
                        n["ring_none_ok" + tag] = bool(s_ >= NO_INT)
                    d["ring_measured_positive_pairs" + tag] = int(np.triu(state < NO_INT, 1).sum())
                    if two:  # the interface as RING sees it: inter-chain contacts (all of them, not only the requested), by class
                        mi = np.triu((state >= INTER_OFFSET) & (state < NO_INT), 1)
                        d["ring_inter_pairs" + tag] = int(mi.sum())
                        d["ring_inter_by_class" + tag] = {G.TYPES[t]: int((state[mi] % INTER_OFFSET == t).sum()) for t in range(len(G.TYPES)) if int((state[mi] % INTER_OFFSET == t).sum())}
                if maps_out is not None:  # every STRICT-window RING-measured positive pair of the design (1-based [i, j, state 0..10]): lets a caller score ANY pair, not only the requested ones
                    state = states[""]
                    ii_, jj_ = np.where(np.triu(state < NO_INT, 1))
                    maps_out[nm] = [[int(i) + 1, int(j) + 1, int(state[i, j])] for i, j in zip(ii_, jj_)]
                d["ring_measured"] = True
                n_ok += 1
            except Exception as e:  # noqa: BLE001
                _clear_ring(d)  # nothing partial survives, at any window
                d["ring_measured"] = False
                d["ring_error"] = f"{type(e).__name__}: {str(e)[:200]}" + ("" if cur is None and len(windows) == 1 else f" (RING {w_label(cur)})" if cur is not None else "")
            d["ring_windows"] = list(tags)
            d["summary"] = summarise_design(d)
    finally:
        import shutil

        shutil.rmtree(root, ignore_errors=True)
    designs = report["designs"]
    failed = [d["design"] for d in designs if not d.get("ring_measured", False)]
    report["aggregate"] = aggregate_report(designs, spec)
    try:
        version = G.ring_version(ring_bin)
    except Exception as e:  # noqa: BLE001
        version = f"unavailable ({type(e).__name__})"
    settings = [{"w": w, "tag": tag, "label": w_label(w), "w_setting": "binary default (-w omitted)" if w is None else f"explicit -w {w:g}",
                 "flags": list(G.RING_FLAGS) + ([] if w is None else ["-w", repr(float(w))]), "role": "strict (ring_ok)" if w is None else "tolerant (headline)" if w == max(x for x in windows if x is not None) else "tolerant"}
                for w, tag in zip(windows, tags)]
    headline = next((f"ring_ok{x['tag']} ({x['label']})" for x in reversed(settings) if x["w"] is not None), "ring_ok (strict RING window)")
    report["ring"] = {"checked": True, "ok": not failed, "n_designs": len(designs), "n_designs_measured": n_ok, "n_designs_failed": len(failed), "failed_designs": failed,
                      "errors": {d["design"]: d["ring_error"] for d in designs if "ring_error" in d}, "binary": ring_bin, "version": version, "flags": list(G.RING_FLAGS), "windows": [w for w in windows],
                      "settings": settings, "headline": headline, "window_note": RING_W_NOTE,
                      "per_design": [{"design": d["design"], "measured": bool(d.get("ring_measured")), "n_requested": len(d["contacts"]) + len(d["negatives"]),
                                      "n_measured": sum("ring_ok" in c for c in d["contacts"]) + sum("ring_none_ok" in n for n in d["negatives"])} for d in designs],
                      "denominator": "every ring_* rate counts ALL requested designs: a design whose RING step failed (at any window) is NOT satisfied; *_measured_only = over the measured designs only"}
    finalize_status(report)
    mem["report.json"] = json.dumps(report, indent=1, default=float).encode()
    write_tar(tar_path, mem)
    return report


def parse_args(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run", help="sample, decode all-atom, write the tar")
    r.add_argument("--spec", required=True, help="JSON file or JSON text")
    r.add_argument("--ckpt", default="")
    r.add_argument("--bundle", default="")
    r.add_argument("--arm", required=True, choices=("A", "B", "C", "Z"), help="A | B | C (Z is the all-MASK control: refused, it never shows the requested pairs)")
    r.add_argument("--out-tar", default=os.environ.get("OUT_TAR", ""))
    r.add_argument("--micro-batch", type=int, default=8, help="designs per sampler batch (>= 1)")
    r.add_argument("--tsr-k", type=float, default=1.5)
    r.add_argument("--gen-overrides", action="append", default=[], help="Hydra override(s) of the composed inference config; repeatable, each value may hold several space-separated overrides (CPU plumbing: --gen-overrides generation.args.nsteps=20 --gen-overrides generation.n_recycle_schedule=null --gen-overrides generation.n_recycle=1)")
    r.add_argument("--configs-dir", default=os.path.join(os.environ.get("PROJECT_ROOT", "/fork"), "configs"))
    r.add_argument("--denovo-cif", default="/opt/rfd4/data/benchmarks/monomer/monomer-short.cif.zst")
    r.add_argument("--device", default=None)
    c = sub.add_parser("ring-check", help="host step: RING 4 measurement of every design; rewrites the tar's report.json; exit 3 if any design could not be measured")
    c.add_argument("--tar", required=True)
    c.add_argument("--ring-bin", default=None)
    c.add_argument("--ring-w", default=None, help="RING windows, comma list: 'none' = the binary's default (STRICT: ring_ok), numbers = explicit -w (ring_ok_w<w>); default: env DWC_RING_W, else the spec's ring_w, else 'none,0.25'")
    a = p.parse_args(argv)
    if a.cmd == "ring-check" and a.ring_w is not None:
        try:
            parse_ring_w(a.ring_w)
        except ValueError as e:
            p.error(str(e))
    if a.cmd == "run":
        if a.arm == "Z":
            p.error("arm Z is the all-MASK control (its sampler never shows the stream): the requested contacts would not be pinned; use arm A, B or C")
        if bool(a.ckpt) == bool(a.bundle):
            p.error("give exactly one of --ckpt / --bundle")
        if not a.out_tar:
            p.error("--out-tar (or env OUT_TAR) is required")
        if not math.isfinite(a.tsr_k) or a.tsr_k <= 0:
            p.error("--tsr-k must be a finite number > 0")
        if a.micro_batch < 1:
            p.error("--micro-batch must be >= 1")
        if a.device is None:
            import torch

            a.device = "cuda" if torch.cuda.is_available() else "cpu"
    return a


def main(argv=None) -> int:
    """CLI entry: returns the exit code (0 ok, 2 bad spec/arguments/environment, 3 RING step failed, 4 pin verification failed); every failure prints a ``DWC FAIL`` line."""
    a = parse_args(argv)
    if a.cmd == "run":
        try:
            rep = run(a)
        except ValueError as e:  # bad spec / refused model / refused environment: nothing was sampled
            print(f"DWC FAIL: {e}", flush=True)
            return EXIT_BAD
        except RuntimeError as e:  # a run that could not produce what the spec asks for (decode mismatch, wrong design count, device audit)
            print(f"DWC FAIL: {e}", flush=True)
            return 1
        st = rep.get("status", {"ok": bool(rep.get("pins_verified", {}).get("ok")), "failures": ["pins_verified.ok is false"]})
        if not st["ok"]:
            for f in st["failures"]:
                print(f"DWC FAIL: {f}", flush=True)
            return EXIT_PINS
        return 0
    try:
        rep = ring_check(a.tar, a.ring_bin, ring_w="auto" if a.ring_w is None else a.ring_w)
    except Exception as e:  # noqa: BLE001
        print(f"DWC FAIL: ring-check could not run: {type(e).__name__}: {e}", flush=True)
        return EXIT_RING
    ms = rep["aggregate"]["mean_design_summary"]
    log(f"ring-check: {rep['ring']['n_designs_measured']}/{rep['ring']['n_designs']} designs measured (rates over ALL designs, unmeasured = unsatisfied); " + " ".join(f"{k}={v:.3f}" for k, v in ms.items() if v is not None))
    for st in rep["ring"]["settings"]:
        log(f"class satisfaction under the {st['label']} [{st['role']}]: contacts_ring_ok{st['tag']}={ms.get('contacts_ring_ok' + st['tag'])} negatives_ring_none_ok{st['tag']}={ms.get('negatives_ring_none_ok' + st['tag'])}"
            f"  per class: " + " ".join(f"{c}={r.get('ring_ok' + st['tag'])}" for c, r in rep["aggregate"]["by_class"].items()))
    log(f"headline: {rep['ring']['headline']}")
    if not rep["ring"]["ok"]:
        print(f"DWC FAIL: RING measurement failed for {rep['ring']['n_designs_failed']}/{rep['ring']['n_designs']} designs {rep['ring']['failed_designs']}: {rep['ring']['errors']}", flush=True)
        for f in rep["status"]["failures"]:
            if f.startswith("pin verification"):
                print(f"DWC FAIL: {f}", flush=True)
        return EXIT_RING
    if not rep["status"]["ok"]:  # the RING step is fine, but the archive still carries a failed pin verification of the sampler run: a re-measurement does not heal it
        for f in rep["status"]["failures"]:
            print(f"DWC FAIL: {f}", flush=True)
        return EXIT_PINS
    return 0


if __name__ == "__main__":
    sys.exit(main())
