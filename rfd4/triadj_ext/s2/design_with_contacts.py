# ------------------------------------------------------------------------------------------------------------------ spec
def class_state(name: str) -> int:
    """'hbond' -> 0 ... 'any' -> 7 (vdw); raises ValueError listing the allowed names (ionic / metal / halogen are refused with the reason)."""
    key = str(name).strip().lower()
    key = ALIASES.get(key, key)
    if key in UNMEASURABLE:
        raise ValueError(f"contact class {name!r} cannot be satisfied or measured on a protein-only design ({UNMEASURABLE[key]}); allowed: {list(ALLOWED_CLASSES)}")
    if key == ANY_CLASS:
        return ANY_STATE
    if key in TYPE_NAMES:
        return TYPE_NAMES.index(key)
    raise ValueError(f"unknown contact class {name!r}; allowed: {list(ALLOWED_CLASSES)}")


def contact_state(name: str, inter: bool = False) -> int:
    """class name -> label state: the intra-chain state 0..10 (``class_state``) or, for a pair across the two chains of a complex, the inter-chain state 11..21 (= + 11; ``any`` -> 18)."""
    try:
        st = class_state(name)
    except ValueError as e:
        if inter:
            raise ValueError(f"{e} (inter-chain contacts use the same class names; their states are 11 + type = {list(INTER_NAMES)}, the unsatisfiable ones are rejected as for a single chain)") from e
        raise
    return st + (INTER_OFFSET if inter else 0)


def _number(name: str, v, lo=None, hi=None, positive=False) -> float:
    """finite real number (JSON numbers only: no bool, no numeric string such as "nan") within the bounds."""
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        raise ValueError(f"{name} must be a number, got {v!r}")
    x = float(v)
    if not math.isfinite(x):
        raise ValueError(f"{name} must be finite, got {v!r}")
    if positive and x <= 0:
        raise ValueError(f"{name} must be a finite number > 0, got {v!r}")
    if lo is not None and x < lo:
        raise ValueError(f"{name} must be a finite number >= {lo}, got {v!r}")
    if hi is not None and x > hi:
        raise ValueError(f"{name} must be <= {hi}, got {v!r}")
    return x


def _integer(name: str, v, lo: int, hi: int | None = None) -> int:
    if isinstance(v, bool) or not isinstance(v, int):
        raise ValueError(f"{name} must be an integer, got {v!r}")
    if v < lo or (hi is not None and v > hi):
        raise ValueError(f"{name} must be in [{lo}, {hi}]" if hi is not None else f"{name} must be >= {lo}")
    return int(v)


def load_spec(spec) -> dict:
    """dict / JSON text / path -> validated, normalised spec (1-based pairs sorted i < j, defaults filled). Raises ValueError with a message naming the offending entry.
    Accepts its own normalised output (contacts / negatives as {"i", "j", "class", "state"} dicts; ``warnings`` is ignored and regenerated): ``load_spec(json.dumps(load_spec(raw))) == load_spec(raw)``."""
    if isinstance(spec, (str, os.PathLike)):
        text = str(spec)
        spec = json.loads(text) if text.lstrip().startswith("{") else json.load(open(text))
    if not isinstance(spec, dict):
        raise ValueError("the spec must be a JSON object")
    s = dict(spec)
    unknown = sorted(set(s) - SPEC_KEYS)
    if unknown:
        raise ValueError(f"unknown spec keys {unknown}")
    chains = s.get("chains")
    if chains is not None:
        if (not isinstance(chains, (list, tuple)) or len(chains) != 2 or any(isinstance(x, bool) or not isinstance(x, int) for x in chains) or any(x < MIN_CHAIN for x in chains)):
            raise ValueError(f"chains must be [L1, L2] with two integers >= {MIN_CHAIN} (two-chain complexes only), got {chains!r}")
        chains = [int(x) for x in chains]
        L = chains[0] + chains[1]
        if "length" in s and s["length"] != L:
            raise ValueError(f"length ({s['length']!r}) must be omitted or equal L1 + L2 = {L} when chains is given")
        if not 20 <= L <= 400:
            raise ValueError(f"L1 + L2 must be in [20, 400], got {L}")
    else:
        L = s.get("length")
        if not isinstance(L, int) or isinstance(L, bool) or not 20 <= L <= 400:
            raise ValueError(f"length must be an integer in [20, 400], got {L!r}")
    out = {"length": L, "name": str(s.get("name", "design")), "n_designs": _integer("n_designs", s.get("n_designs", 4), 1, 64), "seed": _integer("seed", s.get("seed", 0), 0),
           "label_temp": _number("label_temp", s.get("label_temp", 0.5), lo=0.0), "lag": _number("lag", s.get("lag", 0.4), lo=0.0, hi=1.0),
           "cfg_w": _number("cfg_w", s.get("cfg_w", 1.0), positive=True), "mode": str(s.get("mode", "pinned")), "contacts": [], "negatives": [], "warnings": []}
    if chains is not None:
        out["chains"] = chains
    if "ring_w" in s and s["ring_w"] is not None:  # optional: the RING windows of the ring-check step (kept out of the normalised spec when absent: existing specs round-trip unchanged)
        out["ring_w"] = parse_ring_w(s["ring_w"])
    if out["mode"] not in MODES:
        raise ValueError(f"mode must be one of {MODES}")
    seen = {}

    L1 = chains[0] if chains is not None else None

    def as_list(p, what):
        decl = {}
        if isinstance(p, dict):  # the normalised form written to spec.json
            extra = sorted(set(p) - {"i", "j", "class", "state", "inter"})
            if extra or "i" not in p or "j" not in p:
                raise ValueError(f"{what} {p!r}: expected keys i, j{', class' if what == 'contact' else ''} (got {sorted(p)})")
            decl = {k: p[k] for k in ("state", "inter") if k in p}
            if what == "contact":
                return [p["i"], p["j"], p.get("class", ANY_CLASS)], decl
            return [p["i"], p["j"]], decl
        return p, decl

    def pair(p, what):
        p, decl = as_list(p, what)
        if not isinstance(p, (list, tuple)) or len(p) < 2:
            raise ValueError(f"{what} {p!r}: expected [i, j{', class' if what == 'contact' else ''}]")
        i, j = p[0], p[1]
        if not all(isinstance(x, int) and not isinstance(x, bool) for x in (i, j)):
            raise ValueError(f"{what} {p!r}: residue numbers must be integers (1-based)")
        if not (1 <= i <= L and 1 <= j <= L):
            raise ValueError(f"{what} {p!r}: residue numbers must be in [1, {L}]")
        inter = bool(chains is not None and ((i <= L1) != (j <= L1)))
        if "inter" in decl and (not isinstance(decl["inter"], bool) or decl["inter"] != inter):
            raise ValueError(f"{what} {p!r}: inter={decl['inter']!r} does not match the chains {chains} (global numbering: chain A = 1..L1, chain B = L1+1..L1+L2)")
        if not inter and abs(i - j) < MIN_SEP:
            raise ValueError(f"{what} {p!r}: |i-j| must be >= {MIN_SEP} inside a chain (RING reports no closer pair)")
        i, j = min(i, j), max(i, j)
        if (i, j) in seen:
            raise ValueError(f"{what} {p!r}: the pair ({i}, {j}) is already given as a {seen[(i, j)]}")
        seen[(i, j)] = what
        if not inter and j - i < WARN_SEP:
            out["warnings"].append(f"{what} ({i}, {j}) is local (|i-j| = {j - i} < {WARN_SEP}): it constrains the helix/turn geometry, not the tertiary fold")
        return i, j, p, inter, decl

    for p in s.get("contacts", []):
        i, j, p, inter, decl = pair(p, "contact")
        cls = p[2] if len(p) > 2 else ANY_CLASS
        st = contact_state(cls, inter)
        if "state" in decl and (isinstance(decl["state"], bool) or not isinstance(decl["state"], int) or decl["state"] != st):
            raise ValueError(f"contact {p!r}: state {decl['state']!r} does not belong to class {cls!r} ({'inter' if inter else 'intra'}-chain state {st})")
        row = {"i": i, "j": j, "class": ANY_CLASS if str(cls).strip().lower() == ANY_CLASS else TYPE_NAMES[class_state(cls)], "state": st}
        if chains is not None:
            row["inter"] = inter
        out["contacts"].append(row)
    for p in s.get("negatives", []):
        i, j, _, inter, _decl = pair(p, "negative")
        row = {"i": i, "j": j}
        if chains is not None:
            row["inter"] = inter
        out["negatives"].append(row)
    if chains is not None and not any(c["inter"] for c in out["contacts"]):
        out["warnings"].append("no inter-chain contact requested: the two chains are designed without any requested interface")
    if not out["contacts"] and not out["negatives"]:
        raise ValueError("give at least one contact or negative")
    return out


def pinned_map(spec: dict) -> np.ndarray:
    """int16 [L, L], symmetric: the requested class state on every contact, 22 on every negative, 24 (not shown) everywhere else."""
    L = spec["length"]
    m = np.full((L, L), UNOBS, dtype=np.int16)
    for c in spec["contacts"]:
        m[c["i"] - 1, c["j"] - 1] = m[c["j"] - 1, c["i"] - 1] = c["state"]
    for n in spec["negatives"]:
        m[n["i"] - 1, n["j"] - 1] = m[n["j"] - 1, n["i"] - 1] = NO_INT
    return m


def pins_of(m: np.ndarray):
    """(i [k], j [k], state [k]) of the shown pairs, i < j (0-based)."""
    ii, jj = np.where(np.triu(m < 23, 1))
    return ii, jj, m[ii, jj].astype(np.int64)


# ------------------------------------------------------------------------------------------------------------------ geometry on a decoded structure
def residues_of(atoms) -> list:
    """AtomArray-like (res_id, ins_code, chain_id, res_name, atom_name, element, coord) -> [{'name', 'atoms': {atom_name: xyz}, 'heavy': [(atom_name, xyz)]}] in chain order (hydrogens dropped)."""
    out, key_of = [], {}
    chain = getattr(atoms, "chain_id", None)
    ins = getattr(atoms, "ins_code", None)
    for k in range(len(atoms.res_name)):
        el = str(atoms.element[k]).upper() if hasattr(atoms, "element") else ""
        if el in ("H", "D"):
            continue
        key = (str(chain[k]) if chain is not None else "", int(atoms.res_id[k]), str(ins[k]) if ins is not None else "")
        r = key_of.get(key)
        if r is None:
            r = key_of[key] = len(out)
            out.append({"name": str(atoms.res_name[k]), "atoms": {}, "heavy": [], "chain": key[0]})
        xyz = np.asarray(atoms.coord[k], dtype=np.float64)
        out[r]["atoms"][str(atoms.atom_name[k])] = xyz
        out[r]["heavy"].append((str(atoms.atom_name[k]), xyz))
    return out


def sequence_of(residues: list) -> str:
    return "".join(THREE_TO_ONE.get(r["name"], "X") for r in residues)


def _min_dist(a, b) -> float:
    if not a or not b:
        return float("nan")
    A = np.array([x[1] for x in a])
    B = np.array([x[1] for x in b])
    return float(np.sqrt(((A[:, None, :] - B[None, :, :]) ** 2).sum(-1)).min())


def _named(res, names):
    return [(n, res["atoms"][n]) for n in names if n in res["atoms"]]


def _centroid(res, names):
    pts = [res["atoms"][n] for n in names if n in res["atoms"]]
    return np.mean(pts, 0) if len(pts) >= max(3, len(names) - 1) else None


def class_geometry_ok(cls: str, ra: dict, rb: dict) -> tuple:
    """Class-specific GEOMETRIC PROXY of a RING class on two decoded residues -> (ok, value, rule). It is a proxy, not RING: the measured RING state is reported separately by ``ring-check``."""
    heavy = _min_dist(ra["heavy"], rb["heavy"])
    if cls in (ANY_CLASS, "vdw"):
        return bool(heavy <= HEAVY_CUT), heavy, f"min heavy-atom distance <= {HEAVY_CUT} A"
    if cls == "hbond":
        d = _min_dist([(n, x) for n, x in ra["heavy"] if n[0] in "NO"], [(n, x) for n, x in rb["heavy"] if n[0] in "NO"])
        return bool(d <= 3.5), d, "N/O ... N/O distance <= 3.5 A"
    if cls in ("salt_bridge", "ionic"):
        best = float("nan")
        for neg, pos in ((ra, rb), (rb, ra)):
            if neg["name"] in NEG_CHARGED and pos["name"] in POS_CHARGED:
                d = _min_dist(_named(neg, NEG_CHARGED[neg["name"]]), _named(pos, POS_CHARGED[pos["name"]]))
                best = d if not np.isfinite(best) else min(best, d)
        return bool(np.isfinite(best) and best <= 4.5), best, "opposite-charge side-chain N/O pair <= 4.5 A"
    if cls == "hydrophobic":
        if ra["name"] not in HYDROPHOBIC or rb["name"] not in HYDROPHOBIC:
            return False, float("nan"), "both residues hydrophobic and side-chain C-C <= 5 A"
        d = _min_dist([(n, x) for n, x in ra["heavy"] if n not in BACKBONE and n.startswith("C")], [(n, x) for n, x in rb["heavy"] if n not in BACKBONE and n.startswith("C")])
        return bool(d <= 5.0), d, "both residues hydrophobic and side-chain C-C <= 5 A"
    if cls == "pi_stack":
        ca, cb = (_centroid(ra, AROMATIC_RING[ra["name"]]) if ra["name"] in AROMATIC_RING else None), (_centroid(rb, AROMATIC_RING[rb["name"]]) if rb["name"] in AROMATIC_RING else None)
        if ca is None or cb is None:
            return False, float("nan"), "both residues aromatic and ring centroids <= 6.5 A"
        d = float(np.linalg.norm(ca - cb))
        return bool(d <= 6.5), d, "both residues aromatic and ring centroids <= 6.5 A"
    if cls == "disulfide":
        d = _min_dist(_named(ra, ("SG",)), _named(rb, ("SG",)))
        return bool(d <= 2.5), d, "SG-SG distance <= 2.5 A"
    return bool(heavy <= HEAVY_CUT), heavy, f"(no class-specific proxy for {cls}) min heavy-atom distance <= {HEAVY_CUT} A"


def interface_summary(residues: list, L1: int) -> dict:
    """Geometry of the A | B interface of a decoded two-chain design (chain A = the first L1 residues): inter-chain CA-CA <= 8 A pairs, residue pairs / atom pairs within 4.5 A (heavy atoms), residues of each chain with
    any heavy atom within 5 A of the other chain, and a buried-surface PROXY ``bsa_proxy_A2`` = SASA(A alone) + SASA(B alone) - SASA(complex) from biotite's Shrake-Rupley on the HEAVY-ATOM model (no hydrogens:
    a proxy, not a reference BSA)."""
    A, B = residues[:L1], residues[L1:]

    def atoms_of(rs):
        xyz, ridx = [], []
        for t, r in enumerate(rs):
            for _, p in r["heavy"]:
                xyz.append(p)
                ridx.append(t)
        return np.array(xyz, dtype=np.float64).reshape(-1, 3), np.array(ridx, dtype=np.int64)

    xa, ra = atoms_of(A)
    xb, rb = atoms_of(B)
    out = {"n_residues_A": len(A), "n_residues_B": len(B)}
    caA = np.array([r["atoms"].get("CA", np.full(3, np.nan)) for r in A], dtype=np.float64).reshape(-1, 3)
    caB = np.array([r["atoms"].get("CA", np.full(3, np.nan)) for r in B], dtype=np.float64).reshape(-1, 3)
    with np.errstate(invalid="ignore"):
        dca = np.linalg.norm(caA[:, None, :] - caB[None, :, :], axis=-1)
        out["n_inter_ca8"] = int((dca <= CA_CUT).sum())
    if len(xa) and len(xb):
        d = np.linalg.norm(xa[:, None, :] - xb[None, :, :], axis=-1)
        ii, jj = np.where(d <= HEAVY_CUT)
        out["n_inter_atom_pairs_4.5"] = int(len(ii))
        out["n_inter_res_pairs_heavy45"] = int(len(set(zip(ra[ii].tolist(), rb[jj].tolist()))))
        i5, j5 = np.where(d <= 5.0)
        out["n_interface_res_A"], out["n_interface_res_B"] = int(len(set(ra[i5].tolist()))), int(len(set(rb[j5].tolist())))
        ea = np.array([n_.strip()[0] for r in A for n_, _ in r["heavy"]])
        eb = np.array([n_.strip()[0] for r in B for n_, _ in r["heavy"]])
        polar = np.isin(ea, ("N", "O"))[:, None] & np.isin(eb, ("N", "O"))[None, :]
        clash = (d < np.where(polar, CLASH_POLAR, CLASH_NONPOLAR)) & ~((ea == "S")[:, None] & (eb == "S")[None, :])
        ci_, cj_ = np.where(clash)
        out["n_inter_clash_atom_pairs"] = int(len(ci_))
        out["n_inter_clash_res_pairs"] = int(len(set(zip(ra[ci_].tolist(), rb[cj_].tolist()))))
    else:
        out.update({"n_inter_atom_pairs_4.5": 0, "n_inter_res_pairs_heavy45": 0, "n_interface_res_A": 0, "n_interface_res_B": 0, "n_inter_clash_atom_pairs": 0, "n_inter_clash_res_pairs": 0})
    try:
        import biotite.structure as struc

        names, ans, cid, rid, xyz = [], [], [], [], []
        for t, r in enumerate(residues):
            for an, p in r["heavy"]:
                names.append(r["name"])
                ans.append(an)
                cid.append("A" if t < L1 else "B")
                rid.append(t + 1)
                xyz.append(p)
        arr = struc.AtomArray(len(names))
        arr.chain_id[:] = cid
        arr.res_id[:] = rid
        arr.res_name[:] = names
        arr.atom_name[:] = ans
        arr.element[:] = [a_.strip()[0] for a_ in ans]
        arr.coord = np.array(xyz, dtype=np.float32)
        a_alone = float(np.nansum(struc.sasa(arr[arr.chain_id == "A"], point_number=200)))
        b_alone = float(np.nansum(struc.sasa(arr[arr.chain_id == "B"], point_number=200)))
        cplx = float(np.nansum(struc.sasa(arr, point_number=200)))
        out["bsa_proxy_A2"] = round(a_alone + b_alone - cplx, 1)
    except Exception as e:  # noqa: BLE001
        out["bsa_proxy_A2"] = None
        out["bsa_error"] = f"{type(e).__name__}: {str(e)[:120]}"
    out["chains_in_contact"] = bool(out["n_inter_res_pairs_heavy45"] >= 1)  # any heavy-atom proximity <= 4.5 A (an exact overlap counts: this is PROXIMITY only)
    out["complex_formed"] = bool(out["n_inter_res_pairs_heavy45"] >= MIN_INTERFACE_RES_PAIRS and out["n_inter_clash_atom_pairs"] == 0)  # a plausible interface: enough contacts and no clash (see CLASH_*)
    return out


def design_report(residues: list, spec: dict) -> dict:
    """Per-design satisfaction of every requested contact / negative (CA, heavy-atom, class proxy). Two-chain specs: ``inter`` per contact / negative and an ``interface`` block (see ``interface_summary``)."""
    L = len(residues)
    out = {"n_residues": L, "contacts": [], "negatives": []}

    def dists(i, j):
        ra, rb = residues[i - 1], residues[j - 1]
        ca = float(np.linalg.norm(ra["atoms"]["CA"] - rb["atoms"]["CA"])) if "CA" in ra["atoms"] and "CA" in rb["atoms"] else float("nan")
        return ra, rb, ca, _min_dist(ra["heavy"], rb["heavy"])

    for c in spec["contacts"]:
        ra, rb, ca, heavy = dists(c["i"], c["j"])
        ok, val, rule = class_geometry_ok(c["class"], ra, rb)
        out["contacts"].append({"i": c["i"], "j": c["j"], "class": c["class"], "res": [ra["name"], rb["name"]], "ca_dist": round(ca, 3), "ca_ok": bool(ca <= CA_CUT), "min_heavy_dist": round(heavy, 3),
                                "heavy_ok": bool(heavy <= HEAVY_CUT), "class_geom_ok": ok, "class_geom_value": None if not np.isfinite(val) else round(val, 3), "class_geom_rule": rule, **({"inter": bool(c["inter"])} if "inter" in c else {})})
    for n in spec["negatives"]:
        ra, rb, ca, heavy = dists(n["i"], n["j"])
        out["negatives"].append({"i": n["i"], "j": n["j"], "res": [ra["name"], rb["name"]], "ca_dist": round(ca, 3), "ca_far_ok": bool(ca > CA_CUT), "min_heavy_dist": round(heavy, 3), "heavy_far_ok": bool(heavy > NEG_HEAVY), **({"inter": bool(n["inter"])} if "inter" in n else {})})
    if spec.get("chains"):
        out["interface"] = interface_summary(residues, spec["chains"][0])
    out["summary"] = summarise_design(out)
    return out


def _rate(vals):
    return None if not vals else float(np.mean([bool(v) for v in vals]))


def summarise_design(d: dict) -> dict:
    """Per-design satisfaction rates. The ``ring_*`` rates exist only once the RING step ran on the design (``ring_measured`` is in ``d``); their denominator is ALL requested contacts / negatives of the design
    (an unmeasured one counts as NOT satisfied), with ``*_n_requested`` / ``*_n_measured`` next to them. One rate per RING window of ``d['ring_windows']`` (field suffix '' = strict default window, '_w0.25' = tolerant)."""
    s = {"n_contacts": len(d["contacts"]), "n_negatives": len(d["negatives"])}
    for k in ("ca_ok", "heavy_ok", "class_geom_ok"):
        s[f"contacts_{k}"] = _rate([x[k] for x in d["contacts"] if k in x])
    for k in ("ca_far_ok", "heavy_far_ok"):
        s[f"negatives_{k}"] = _rate([x[k] for x in d["negatives"] if k in x])
    if "ring_measured" in d:
        for key, items, f in (("contacts", d["contacts"], "ring_ok"), ("negatives", d["negatives"], "ring_none_ok")):
            n = len(items)
            for tag in d.get("ring_windows", [""]):
                s[f"{key}_{f}{tag}"] = None if n == 0 else float(sum(bool(x.get(f + tag, False)) for x in items) / n)
            s[f"{key}_ring_n_requested"] = n
            s[f"{key}_ring_n_measured"] = int(sum(f in x for x in items))
    else:
        s["contacts_ring_ok"] = None
        s["negatives_ring_none_ok"] = None
    return s


def aggregate_report(designs: list, spec: dict) -> dict:
    """Mean satisfaction per requested contact / negative / contact class over the designs. Without a RING step the sampler-side rates are reported; after it the ``ring_*`` rates use ALL designs as the
    denominator (unmeasured = unsatisfied) and ``ring_ok_measured_only`` the measured designs only, with ``ring_n_requested`` / ``ring_n_measured`` beside them."""
    N = len(designs)
    ring = any("ring_measured" in d for d in designs)
    tags = [""]
    for d in designs:
        for t in d.get("ring_windows", [""]):
            if t not in tags:
                tags.append(t)
    agg = {"n_designs": N, "ring_checked": ring, "ring_windows": tags if ring else [], "contacts": [], "negatives": [], "by_class": {}}

    for k, c in enumerate(spec["contacts"]):
        row = {"i": c["i"], "j": c["j"], "class": c["class"]}
        for f in ("ca_ok", "heavy_ok", "class_geom_ok"):
            r = _rate([d["contacts"][k][f] for d in designs if f in d["contacts"][k]])
            if r is not None:
                row[f] = r
        if ring:
            vals = [d["contacts"][k]["ring_ok"] for d in designs if "ring_ok" in d["contacts"][k]]
            row["ring_n_requested"], row["ring_n_measured"] = N, len(vals)
            for tag in tags:
                v_ = [d["contacts"][k]["ring_ok" + tag] for d in designs if "ring_ok" + tag in d["contacts"][k]]
                row["ring_ok" + tag] = float(sum(bool(v) for v in v_) / N) if N else None
                row["ring_ok" + tag + "_measured_only"] = _rate(v_)
        agg["contacts"].append(row)
    for k, n in enumerate(spec["negatives"]):
        row = {"i": n["i"], "j": n["j"]}
        for f in ("ca_far_ok", "heavy_far_ok"):
            r = _rate([d["negatives"][k][f] for d in designs if f in d["negatives"][k]])
            if r is not None:
                row[f] = r
        if ring:
            vals = [d["negatives"][k]["ring_none_ok"] for d in designs if "ring_none_ok" in d["negatives"][k]]
            row["ring_n_requested"], row["ring_n_measured"] = N, len(vals)
            for tag in tags:
                v_ = [d["negatives"][k]["ring_none_ok" + tag] for d in designs if "ring_none_ok" + tag in d["negatives"][k]]
                row["ring_none_ok" + tag] = float(sum(bool(v) for v in v_) / N) if N else None
                row["ring_none_ok" + tag + "_measured_only"] = _rate(v_)
        agg["negatives"].append(row)
    lab = lambda c: ("inter_" if c.get("inter") else "") + c["class"]  # two-chain specs: intra and inter classes are separate rows (monomer specs: unchanged)
    for cls in sorted({lab(c) for c in spec["contacts"]}):
        ks = [k for k, c in enumerate(spec["contacts"]) if lab(c) == cls]
        row = {"n_contacts": len(ks), "n_requested": len(ks) * N}
        for f in ("ca_ok", "heavy_ok", "class_geom_ok"):
            row[f] = _rate([d["contacts"][k][f] for d in designs for k in ks if f in d["contacts"][k]])
        if ring:
            vals = [d["contacts"][k]["ring_ok"] for d in designs for k in ks if "ring_ok" in d["contacts"][k]]
            row["n_measured"] = len(vals)
            for tag in tags:
                v_ = [d["contacts"][k]["ring_ok" + tag] for d in designs for k in ks if "ring_ok" + tag in d["contacts"][k]]
                row["ring_ok" + tag] = float(sum(bool(v) for v in v_) / row["n_requested"]) if row["n_requested"] else None
                row["ring_ok" + tag + "_measured_only"] = _rate(v_)
        agg["by_class"][cls] = row
    if spec.get("chains"):
        ifs = [d["interface"] for d in designs if "interface" in d]
        agg["interface"] = {"n_designs": len(ifs), "frac_complex_formed": _rate([x["complex_formed"] for x in ifs]), "frac_chains_in_contact": _rate([x["chains_in_contact"] for x in ifs]),
                            "frac_with_clash": _rate([x["n_inter_clash_atom_pairs"] > 0 for x in ifs])}
        for k in ("n_inter_ca8", "n_inter_res_pairs_heavy45", "n_inter_atom_pairs_4.5", "n_inter_clash_atom_pairs", "n_interface_res_A", "n_interface_res_B", "bsa_proxy_A2"):
            v_ = [x[k] for x in ifs if x.get(k) is not None]
            agg["interface"][k] = {"mean": float(np.mean(v_)), "min": float(np.min(v_)), "max": float(np.max(v_))} if v_ else None
        if ring:
            for tag in tags:
                v_ = [d["ring_inter_pairs" + tag] for d in designs if "ring_inter_pairs" + tag in d]
                agg["interface"]["ring_inter_pairs" + tag] = {"mean": float(np.mean(v_)), "min": float(np.min(v_)), "max": float(np.max(v_)), "n_measured": len(v_), "n_requested": N} if v_ else None
    keys = sorted({k for d in designs for k in d["summary"] if k.startswith(("contacts_", "negatives_")) and not k.endswith(("_n_requested", "_n_measured"))})
    agg["mean_design_summary"] = {k: (float(np.mean([d["summary"][k] for d in designs if d["summary"].get(k) is not None])) if any(d["summary"].get(k) is not None for d in designs) else None) for k in keys}
    return agg


# ------------------------------------------------------------------------------------------------------------------ guards, status
def check_environment(mode: str) -> None:
    """This tool sets the sampler mode itself (pinned / hybrid): an inherited ``TRIADR_RING_SAMPLER`` (e.g. ``masked``) is refused instead of silently overridden or, worse, honoured."""
    if os.environ.get("TRIADR_RING_ALLOW_INTER", "").strip().lower() in ("1", "true", "yes"):
        raise ValueError("TRIADR_RING_ALLOW_INTER is set in the environment: it switches the inter-chain class restrictions of the sampler off (a diagnosis knob); unset it")
    v = os.environ.get("TRIADR_RING_SAMPLER", "").strip().lower()
    if v and v != mode:
        raise ValueError(f"TRIADR_RING_SAMPLER={v!r} is set in the environment but this tool runs the {mode!r} sampler: unset it (a 'masked' / 'generated' override would hide the requested pairs)")


def check_pin_capable(model) -> None:
    """Refuse a model whose flow matcher forces a sampler mode (arm Z forces ``masked``: the requested pairs would never be shown)."""
    forced = getattr(getattr(model, "fm", None), "force_sampler_mode", None)
    if forced:
        raise ValueError(f"this model's flow matcher forces the {forced!r} sampler (arm Z / control): the requested pairs would never be shown; use an arm A, B or C checkpoint")


def finalize_status(report: dict) -> dict:
    """report['status'] = {'ok', 'failures'}: pin verification failed, or the RING step ran and failed for at least one design. Returns the status."""
    fails = []
    pv = report.get("pins_verified", {})
    if not pv.get("ok", False):
        fails.append(f"pin verification failed (violations={pv.get('violations')}, final_state_ok={pv.get('final_state_ok')}, steps_checked={pv.get('steps_checked')})"
                     + (" [masked control: every valid off-diagonal pair of the stream must be MASK at every step; violations = revealed entries]" if pv.get("control") else ""))
    r = report.get("ring", {})
    if r.get("checked") and not r.get("ok", False):
        fails.append(f"RING measurement failed for {r.get('n_designs_failed')}/{r.get('n_designs')} designs: {r.get('failed_designs')}")
    report["status"] = {"ok": not fails, "failures": fails}
    return report["status"]


# ------------------------------------------------------------------------------------------------------------------ device audit (GPU round: the CPU-built batch met the CUDA encoder)
def _same_device(d, device) -> bool:
    return d.type == device.type and (device.index is None or d.index is None or d.index == device.index)


def tensors_off_device(obj, device, path: str = "batch", _seen=None, _out=None, limit: int = 40) -> list:
    """Every tensor leaf of ``obj`` (PaddedBatchedDataSample dataclass fields AND its runtime ``_extra_fields``, dicts, lists, tuples) that is NOT on ``device`` -> ['batch.coords: cpu', ...] (first ``limit``)."""
    import dataclasses

    import torch

    _seen = set() if _seen is None else _seen
    _out = [] if _out is None else _out
    if id(obj) in _seen or len(_out) >= limit:
        return _out
    _seen.add(id(obj))
    if torch.is_tensor(obj):
        if not _same_device(obj.device, device):
            _out.append(f"{path}: {obj.device}")
    elif dataclasses.is_dataclass(obj) and not isinstance(obj, type):
        for f in dataclasses.fields(obj):
            tensors_off_device(getattr(obj, f.name, None), device, f"{path}.{f.name}", _seen, _out, limit)
        extra = getattr(obj, "_extra_fields", None)  # keys added with batch[key] = value live OUTSIDE the dataclass fields
        if isinstance(extra, dict):
            tensors_off_device(extra, device, f"{path}._extra_fields", _seen, _out, limit)
    elif isinstance(obj, dict):
        for k, v in obj.items():
            tensors_off_device(v, device, f"{path}[{k!r}]", _seen, _out, limit)
    elif isinstance(obj, (list, tuple)):
        for i, v in enumerate(obj):
            if torch.is_tensor(v) or isinstance(v, (dict, list, tuple)) or dataclasses.is_dataclass(v):
                tensors_off_device(v, device, f"{path}[{i}]", _seen, _out, limit)
    return _out


def move_batch(batch, device):
    """The transfer ``Trainer.predict`` applies to a PaddedBatchedDataSample (lightning's move_data_to_device: dataclass fields -> device, atom arrays / ids untouched). NOTE: keys added with
    ``batch[key] = value`` are NOT dataclass fields and are not moved: put them on ``device`` yourself, AFTER this call."""
    try:
        from lightning.fabric.utilities.apply_func import move_data_to_device
    except ImportError:  # pragma: no cover
        import torch
        from lightning_utilities import apply_to_collection

        def move_data_to_device(b, d):
            return apply_to_collection(b, torch.Tensor, lambda x: x.to(d))
    return move_data_to_device(batch, device)


def check_batch_on_device(batch, device) -> None:
    bad = tensors_off_device(batch, device)
    if bad:
        raise RuntimeError(f"{len(bad)}+ batch tensors are off the model device {device}: {bad[:12]}")


def check_model_on_device(model, device) -> None:
    bad = [f"{n}: {p.device}" for n, p in list(model.named_parameters()) + list(model.named_buffers()) if not _same_device(p.device, device)]
    if bad:
        raise RuntimeError(f"{len(bad)} model tensors are off the model device {device}: {bad[:12]}")


# ------------------------------------------------------------------------------------------------------------------ pin verification and the map
def install_pin_check(fm, pins: tuple, device, control: bool = False):
    """Wrap ``fm.get_clean_pred_n_guided_vector`` (instance attribute) so that at EVERY sampler step the pinned pairs are verified in ``batch['ring_state']`` BEFORE the denoiser sees them.
    ``control=True`` (the masked-control mode of dwc_class_fidelity: the stream must be ALL-MASK): instead EVERY valid off-diagonal pair of the stream input (both orientations, requested or not) must be MASK
    at EVERY step; ``violations`` counts the entries that are NOT (any revealed label, right or wrong, requested or not), ``checked_pairs`` the entries inspected: a verified control has violations == 0.
    -> (stats {'steps', 'violations', 'checked_pairs'}, restore())."""
    import torch

    ii, jj, st = pins
    ii_t, jj_t, st_t = (torch.as_tensor(x, device=device, dtype=torch.long) for x in (ii, jj, st))
    stats = {"steps": 0, "violations": 0, "checked_pairs": 0}
    orig = fm.get_clean_pred_n_guided_vector

    def checked(batch, predict_for_sampling, guidance_w):
        check_batch_on_device(batch, device)  # every tensor the denoiser is about to see (x_t, t, ring_state, coords, ...) is on the model device, or fail with the names
        rs = batch["ring_state"]
        stats["steps"] += 1
        if control:
            pm = batch["padding_mask"].bool()
            valid = pm[:, :, None] & pm[:, None, :] & ~torch.eye(pm.shape[1], dtype=torch.bool, device=pm.device)[None]
            stats["checked_pairs"] += int(valid.sum())
            stats["violations"] += int(((rs != CONTROL_MASK) & valid).sum())
            return orig(batch, predict_for_sampling, guidance_w)
        got = rs[:, ii_t, jj_t]
        got2 = rs[:, jj_t, ii_t]
        stats["checked_pairs"] += int(got.numel()) * 2
        stats["violations"] += int((got != st_t[None]).sum()) + int((got2 != st_t[None]).sum())
        return orig(batch, predict_for_sampling, guidance_w)

    fm.get_clean_pred_n_guided_vector = checked

    def restore():
        fm.get_clean_pred_n_guided_vector = orig

    return stats, restore


def final_state_ok(finals: list, pins: tuple, control: bool = False) -> bool:
    """Final stream state of every design: pinned / hybrid = every requested pair carries its label; masked control = EVERY off-diagonal pair is still MASK (a missing record is not a verification)."""
    if control:
        return all(f is not None and bool((f[~np.eye(f.shape[0], dtype=bool)] == CONTROL_MASK).all()) for f in finals)
    return all(f is None or bool((f[pins[0], pins[1]] == pins[2]).all()) for f in finals)


def map_record(final_state: np.ndarray | None, spec: dict) -> dict:
    """map.json entry: the pinned pairs and (hybrid) the positive pairs of the final map as 1-based [i, j, class]."""
    rec = {"pinned": [[c["i"], c["j"], ("inter_" if c.get("inter") else "") + c["class"]] for c in spec["contacts"]] + [[n["i"], n["j"], "no_interaction"] for n in spec["negatives"]]}
    if final_state is not None:
        ii, jj = np.where(np.triu((final_state >= 0) & (final_state < NO_INT), 1))
        rec["final_positive_pairs"] = [[int(i) + 1, int(j) + 1, ("inter_" if int(final_state[i, j]) >= INTER_OFFSET else "") + TYPE_NAMES[int(final_state[i, j]) % 11]] for i, j in zip(ii, jj)]
        rec["final_n_positive"] = len(ii)
        rec["final_n_masked"] = int((final_state == 23).sum()) // 2
    return rec


# ------------------------------------------------------------------------------------------------------------------ tar
def pdb_text(atoms) -> str:
    """Plain AtomArray -> PDB text via biotite (the decoded array carries many custom annotations the PDB writer cannot take: only the standard ones are copied)."""
    import biotite.structure as struc
    import biotite.structure.io.pdb as pdb

    n = atoms.array_length()
    a = struc.AtomArray(n)
    for ann in ("chain_id", "res_id", "ins_code", "res_name", "atom_name", "element", "hetero"):
        a.set_annotation(ann, np.asarray(getattr(atoms, ann)))
    a.coord = np.asarray(atoms.coord, dtype=np.float32)
    f = pdb.PDBFile()
    f.set_structure(a)
    buf = io.StringIO()
    f.write(buf)
    return buf.getvalue()


def write_tar(path: str, members: dict) -> None:
    """``members`` {name: str | bytes} -> gz tar written in memory (no per-member files)."""
    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    tmp = path + ".tmp"
    with tarfile.open(tmp, "w:gz") as tf:
        for name, data in members.items():
            b = data.encode() if isinstance(data, str) else data
            ti = tarfile.TarInfo(name)
            ti.size, ti.mtime = len(b), int(time.time())
            tf.addfile(ti, io.BytesIO(b))
    os.replace(tmp, path)


def read_tar(path: str) -> dict:
    out = {}
    with tarfile.open(path, "r:gz") as tf:
        for m in tf.getmembers():
            if m.isfile():
                out[m.name] = tf.extractfile(m).read()
    return out


