def parse_ring_w(x) -> list:
    """'none,0.25' | [None, 0.25] | ['default', 0.25] -> [None, 0.25]: RING ``-w`` settings; None = the binary's omitted (default, STRICT) window, which MUST be present (``ring_ok`` keeps its strict meaning) and comes
    first; explicit values are finite numbers > 0; no duplicates."""
    toks = [t for t in x.split(",")] if isinstance(x, str) else list(x)
    out = []
    for t in toks:
        if isinstance(t, str):
            t = t.strip().lower()
            t = None if t in ("", "none", "default", "null") else t
        if t is not None:
            if isinstance(t, bool) or not isinstance(t, (int, float, str)):
                raise ValueError(f"ring_w entries must be 'none' or numbers > 0, got {t!r}")
            try:
                t = float(t)
            except ValueError as e:
                raise ValueError(f"ring_w entries must be 'none' or numbers > 0, got {t!r}") from e
            if not math.isfinite(t) or t <= 0:
                raise ValueError(f"ring_w entries must be 'none' or finite numbers > 0, got {t!r}")
        out.append(t)
    if len(set(out)) != len(out):
        raise ValueError(f"ring_w lists a window twice: {x!r}")
    if None not in out:
        raise ValueError(f"ring_w must include 'none' (the strict default window: ring_ok keeps its meaning), got {x!r}")
    return [None] + sorted(t for t in out if t is not None)


def w_tag(w) -> str:
    """field suffix of a RING window: '' (strict default window) | '_w0.25'."""
    return "" if w is None else f"_w{w:g}"


def w_label(w) -> str:
    return "strict RING window (binary default, -w omitted)" if w is None else f"tolerant RING window -w {w:g}"


def run_ring_w(pdb_path: str, out_dir: str, ring_bin: str, w) -> str:
    """``gate_c.run_ring`` with an explicit RING ``-w`` (max atom-surface distance of a vdw edge, Angstrom) when ``w`` is not None; ``None`` = the binary's omitted default (exactly gate_c.run_ring, as the designs
    were always measured)."""
    import subprocess
    from pathlib import Path

    from triadj_ext.s2 import gate_c as G

    if w is None:
        return G.run_ring(pdb_path, out_dir, ring_bin)
    os.makedirs(out_dir, exist_ok=True)
    cp = subprocess.run([ring_bin, "-i", pdb_path, "--out_dir", out_dir, *G.RING_FLAGS, "-w", repr(float(w))], capture_output=True, text=True, timeout=300.0)
    if cp.returncode != 0:
        raise RuntimeError(f"ring exit {cp.returncode}: {(cp.stderr or cp.stdout)[-300:]}")
    hits = [f for f in os.listdir(out_dir) if f.endswith("_ringEdges")]
    if not hits:
        raise RuntimeError("ring wrote no *_ringEdges file")
    return Path(out_dir, hits[0]).read_text()


